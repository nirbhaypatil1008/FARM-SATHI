/**
 * Translate a key string into the target language.
 * Falls back to English / original key if no translation exists.
 */
export function t(key, language = 'en') {
  if (!key) return ''
  if (!language || language === 'en') return key
  const entry = DICTIONARY[key]
  if (entry && entry[language]) {
    return entry[language]
  }
  return key
}

